#!/usr/bin/env python3
"""Collect the files to print into one folder per Core body (owner, 2026-11-21: "less confusing"):

  python3 tools/print_set.py [dest]          (default out/print)
  -> dest/lens/*.stl, dest/slim/*.stl, dest/README.md

Each body's folder holds its Core body with its two plugs and the Docks made for it: B MONO and D TILE. Only parts
to print; the stand-ins the scripts write for the interference checks (core-*, magnets, boards) are left out.
Run tools/enclosure.py (both bodies) and tools/dock_print.py (both bodies, tile and mono) first.
"""
import pathlib
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MECH = ROOT / "mechanical"
DEST = pathlib.Path(sys.argv[1]).expanduser() if len(sys.argv) > 1 else ROOT / "out" / "print"
CORE = {"lens": MECH / "core", "slim": MECH / "core" / "slim"}
# name in the print folder: (source folder, file)
PARTS = {
    "core-body.stl": ("core", "maratus-core-body.stl"),
    "core-plug-lock.stl": ("core", "plug-lock.stl"),
    "core-plug-usb.stl": ("core", "plug-usb.stl"),
    "mono-foot.stl": ("mono", "foot.stl"),
    "mono-plate.stl": ("mono", "plate.stl"),
    "mono-drawer.stl": ("mono", "drawer.stl"),
    "tile-shell.stl": ("tile", "shell.stl"),
    "tile-plate.stl": ("tile", "plate.stl"),
    "tile-drawer.stl": ("tile", "drawer.stl"),
}
README = """# Maratus print files

One folder per Core body. Print only from the folder of the body you print: a Dock fits only that body.

- `lens/`: the lens body (cover glass, 12 mm corners), with B MONO SOFT and D TILE.
- `slim/`: the slim body (glass to the edge, 3 mm corners), with B MONO SHARP and D TILE.

| File | Part | Notes |
| --- | --- | --- |
| `core-body.stl` | Core body | Two 10 x 2 mm magnets glued into its floor from the inside. |
| `core-plug-lock.stl`, `core-plug-usb.stl` | Plugs | Soft material (TPU). |
| `mono-foot.stl` | B MONO foot | Print standing on its open bottom. SOFT: supports inside the curved back. |
| `mono-plate.stl` | B MONO base plate | Four countersunk M2 screws into the foot, two into the drawer. |
| `mono-drawer.stl` | B MONO port drawer | Slides into the rear wall, flush. |
| `tile-shell.stl` | D TILE shell | Print standing on its open bottom; supports inside the sloped top. |
| `tile-plate.stl` | D TILE base plate | Orange. Four countersunk M2 screws into the shell, two into the drawer. |
| `tile-drawer.stl` | D TILE port drawer | |

Every Dock takes four magnets 10 x 2 mm N42 (two stacks of two), glued into the pockets from the inside before
the plate goes on, the same pole towards the Core as the Core's magnets need (check with the Core before the glue
sets); and optionally one M4 x 8 bolt into the Core's M4 nut, from inside with the plate off.
The pockets for the Promax contact parts are drawn from Promax's PDF drawings; the parts have not arrived, so
their fit is not tried. Generated by tools/print_set.py from tools/enclosure.py and tools/dock_print.py.
"""


def main():
    for body, core_dir in CORE.items():
        out = DEST / body
        out.mkdir(parents=True, exist_ok=True)
        sources = {"core": core_dir, "mono": MECH / f"dock-{body}-mono", "tile": MECH / f"dock-{body}-tile"}
        for name, (kind, file) in PARTS.items():
            src = sources[kind] / file
            assert src.exists(), f"missing {src}: run the generator first"
            shutil.copy2(src, out / name)
        print(f"{out}: {len(PARTS)} files")
    (DEST / "README.md").write_text(README)


if __name__ == "__main__":
    main()
